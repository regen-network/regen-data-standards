#!/usr/bin/env python3
"""Generate and check the Claim, Evaluation and C06 claim JSON-LD examples,
and the playground JSON-LD.

    python3 scripts/claim-examples.py generate    # rewrite examples/*.jsonld, without checking
    python3 scripts/claim-examples.py check       # fail if anything is stale or wrong
    python3 scripts/claim-examples.py playground [DIR [SCHEMA]]  # write and check DIR/*/*.jsonld

generate only writes the examples, so it runs on a clean checkout. check also
reads the Turtle that gen-rdf and gen-hierarchy write, so run those first.

Run from the schema/ directory. Examples and playground JSON-LD are built
with the published artifacts of the version src/schema.yaml declares
(versions/<version>/, generated by scripts/schema-artifacts.py from
src/schema.yaml and its imports): a document is a YAML fixture plus that
version's JSON-LD context, inline, and an explicit "@type" on the document and
on every nested inlined object, as in the Turtle output. A selector's "@type"
is the class its selectorType names (oa:FragmentSelector or
oa:TextQuoteSelector), which then replaces selectorType.

The check validates every document with both published validators:

- the JSON Schema (json-schema.json) over the authored YAML, with the class as
  entry point (#/$defs/<class>), reporting errors as linkml-validate does;
- the SHACL shapes (shacl.ttl, closed shapes) over the RDF graph of the
  authored JSON-LD, parsed without rdflib's literal normalization so that
  lexical forms, such as the Z suffix of assertedAt, are checked as written.
  Claims and evaluations reference Evidence records by IRI, and Evidence
  records reference Activity records by IRI (wasGeneratedBy); the shapes
  require each to be an rfs:Evidence or an rfs:Activity. So each document is
  checked together with the Turtle gen-rdf wrote for the records it can
  reference, as the graph store holds them: a claim or evaluation with the
  Evidence and Activity records, an Evidence record with the Activity records.
  Activity records are typed with a kind of Activity (GenericActivity,
  Capture), so they are merged together with the class hierarchy gen-hierarchy
  publishes, which the store holds too. An Activity record references no other
  record and is checked on its own.

Each example must be current, its JSON-LD graph isomorphic to the Turtle that
gen-rdf publishes for its fixture (run make gen-rdf first), and accepted by
both validators; the Turtle is checked with SHACL too. The class of a fixture
is the part of its file name before the first "-", as in gen-rdf. Every
examples/*.INVALID-*.yaml document must be rejected by both validators: by JSON
Schema with the error named on its first line ("# expect: ..."), and by SHACL.
Its class is named on a "# class: ..." line, and is GenericClaim when there is
none. A document that breaks a LinkML rule carries a "# shacl: not enforced"
line: the generated SHACL does not express rules, so only JSON Schema must
reject it, and the check reports that SHACL accepts it. The line may give
another reason in parentheses. A document marked "# graph: with the Evidence
records" is valid on its own ("# expect: accepted alone"), and SHACL must
reject it merged with the Evidence records, as the graph store merges it. An
invalid document listed in INVALID_JSONLD is also published as JSON-LD. One
listed in DERIVED_INVALID is written by generate from a valid fixture with one
change, so that every other field stays the valid example's.

generate also writes the records the examples cite by IRI, as one JSON-LD
document per class (RECORDS: examples/records/evidence.jsonld holds every
Evidence fixture, generic-activity.jsonld and capture.jsonld every activity
fixture), which scripts/schema-artifacts.py publishes with the
examples.

For each example with citations, the check also changes a selector and
requires that the cited Evidence IRIs and the Evidence records stay the same,
while the citing document's graph changes.

The generic examples are GenericClaims and GenericEvaluations, whose shapes are
closed. The base Claim and Evaluation are abstract, so their shapes are open:
they check the base content of every claim type or kind of evaluation and let it
add fields. To check that, each generic example is also retyped as a class
defined outside this schema, with a field of its own and the rdfs:subClassOf
triple that such a schema publishes with its data. The open base shape must
accept it, and must reject it without assertedBy.

Every other example (a claim type or a kind of evaluation) is also checked as
the graph store holds it, with the class hierarchy gen-hierarchy publishes, so
the open base shapes apply to it as well as its own closed shape. It must
conform, so the fields it inherits are accepted, and with an undeclared field it
must be rejected by its own shape only, not by a base shape. Run gen-hierarchy
first.

`playground` writes the JSON-LD of every playground fixture (DIR/*/*.yaml,
DIR being data/playground unless given) next to the Turtle that gen-rdf
writes from SCHEMA (src/schema.yaml unless given). For src/schema.yaml it uses
the published context; for another schema, which has no published artifacts,
it generates that schema's context with the same corrections
(scripts/schema-artifacts.py). It checks that the JSON-LD and the Turtle have
the same graph. Numbers are compared by value: a float written as a YAML
integer, such as 500, is "500"^^xsd:float in JSON-LD and "500.0"^^xsd:float in
Turtle.
"""

