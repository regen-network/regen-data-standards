def schema_artifacts():
    """scripts/schema-artifacts.py, loaded as a module (its file name has a dash)."""
    path = Path(__file__).with_name("schema-artifacts.py")
    spec = importlib.util.spec_from_file_location("schema_artifacts", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Bundle:
    """The published artifacts of the version src/schema.yaml declares, or,
    for another schema, its corrected JSON-LD context alone."""

    def __init__(self, schema=SCHEMA):
        self.view = SchemaView(str(schema))
        if Path(schema).resolve() != Path(SCHEMA).resolve():
            context = schema_artifacts().generate_artifact("context", Path(schema))
            self.context = json.loads(context)["@context"]
            self.json_schema = self.shapes = None
            return
        directory = Path("versions") / self.view.schema.version
        if not directory.exists():
            sys.exit(f"{directory} is missing: run make gen-schema-artifacts")
        self.context = json.loads((directory / "context.jsonld").read_text())["@context"]
        self.json_schema = json.loads((directory / "json-schema.json").read_text())
        self.shapes = rdflib.Graph().parse(directory / "shacl.ttl", format="turtle")


def designated_class(view, class_name, data):
    """Return the subclass a type designator (such as selectorType) names."""
    for slot in view.class_induced_slots(class_name):
        if slot.designates_type and slot.name in data:
            for name in view.class_descendants(class_name):
                if view.get_uri(view.get_class(name)) == data[slot.name]:
                    return name, slot.name
    return class_name, None


def typed(view, class_name, data):
    """Return data with "@type" on this object and on nested inlined objects."""
    class_name, designator = designated_class(view, class_name, data)
    out = {"@type": class_name}
    for key, value in data.items():
        if key == designator:
            continue  # stated by "@type"
        try:
            slot = view.induced_slot(key, class_name)
        except ValueError:
            slot = None  # not in the schema: kept, so validation can reject it
        if slot is not None and slot.range in view.all_classes() and view.is_inlined(slot):
            # Non-objects (such as a bare IRI) are kept as written, so
            # validation can reject them.
            if isinstance(value, list):
                value = [typed(view, slot.range, v) if isinstance(v, dict) else v for v in value]
            elif isinstance(value, dict):
                value = typed(view, slot.range, value)
        out[key] = value
    return out


def build(bundle, class_name, source, data=None):
    if data is None:
        data = yaml.safe_load(Path(source).read_text())
    document = {"@context": bundle.context, **typed(bundle.view, class_name, data)}
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def lexical_graph(text, format):
    """Parse RDF keeping lexical forms as written (a Z stays Z, not +00:00)."""
    rdflib.NORMALIZE_LITERALS = False
    try:
        return rdflib.Graph().parse(data=text, format=format)
    finally:
        rdflib.NORMALIZE_LITERALS = True


def published_turtle(fixture):
    """Return the Turtle gen-rdf wrote for a fixture, which update-graph publishes."""
    path = Path(fixture).with_suffix(".ttl")
    if not path.exists():
        sys.exit(f"{path} is missing: run make gen-rdf")
    return path


def json_schema_check(bundle, document, class_name):
    """Validate an authored YAML document with the published JSON Schema."""
    schema = bundle.json_schema
    validator = jsonschema.Draft201909Validator(
        {"$schema": schema["$schema"], "$defs": schema["$defs"], "$ref": f"#/$defs/{class_name}"},
        format_checker=jsonschema.Draft201909Validator.FORMAT_CHECKER,
    )
    data = yaml.safe_load(Path(document).read_text())
    messages = []
    for error in validator.iter_errors(data):
        error = best_match([error])
        messages.append(f"{error.message} in /{'/'.join(str(p) for p in error.absolute_path)}")
    return not messages, "\n".join(messages)


def class_uri(view, name):
    return rdflib.URIRef(view.get_uri(view.get_element(name), expand=True))


def as_extension(view, graph, class_name, without=None):
    """Retype the record as a class defined outside this schema, with a field of its own."""
    uri = lambda name: class_uri(view, name)
    base = OPEN_BASES[class_name]
    extension = rdflib.URIRef(f"https://example.org/schema/Extension{base}")
    out = rdflib.Graph()
    for triple in graph:
        out.add(triple)
    root = next(out.subjects(RDF.type, uri(class_name)))
    out.remove((root, RDF.type, uri(class_name)))
    out.add((root, RDF.type, extension))
    out.add((extension, RDFS.subClassOf, uri(base)))
    out.add((root, EXTENSION_FIELD, rdflib.Literal("claim-type content")))
    if without:
        out.remove((root, uri(without), None))
    return out


def record_store():
    """The Evidence and Activity records as the graph store holds them: gen-rdf's Turtle."""
    store = {}
    for kind, patterns in RECORD_GLOBS.items():
        paths = sorted(path for pattern in patterns for path in glob.glob(pattern))
        if not paths:
            sys.exit(f"No {kind} record Turtle found: run make gen-rdf")
        store[kind] = rdflib.Graph()
        for path in paths:
            store[kind] += lexical_graph(Path(path).read_text(), "turtle")
    # An activity record's type is a kind of Activity: sh:class rfs:Activity
    # holds for it only with the class hierarchy.
    store["activity"] += hierarchy()
    return store


def with_store(graph, store, class_name=None):
    """Return graph merged with the records a document of class_name can reference.

    An Activity record references none. An Evidence record references Activity
    records, and is not merged with the Evidence records, which hold it already:
    merged with itself, its digest (a blank node) would be duplicated."""
    if class_name in ACTIVITY_CLASSES:
        return graph
    merged = rdflib.Graph()
    merged += graph
    merged += store["activity"]
    if class_name != "Evidence":
        merged += store["evidence"]
    return merged


def change_selector(data):
    """Return a copy of data whose first citation with a selector has that selector changed."""
    data = json.loads(json.dumps(data))
    citation = next(c for c in data["hasEvidenceCitation"] if c.get("selector"))
    selector = citation["selector"][0]
    key = "value" if "value" in selector else "exact"
    selector[key] = selector[key] + "-changed"
    return data


def hierarchy():
    if not Path(HIERARCHY).exists():
        sys.exit(f"{HIERARCHY} is missing: run make gen-hierarchy")
    return rdflib.Graph().parse(HIERARCHY, format="turtle")


def with_undeclared_field(view, graph, class_name):
    out = rdflib.Graph()
    out += graph
    root = next(out.subjects(RDF.type, class_uri(view, class_name)))
    out.add((root, UNDECLARED_FIELD, rdflib.Literal("undeclared")))
    return out


def rejecting_shapes(graph, shapes):
    _, results, _ = shacl_validate(graph, shacl_graph=shapes)
    return {results.value(r, SH.sourceShape) for r in results.subjects(RDF.type, SH.ValidationResult)}


def shacl_report(graph, shapes):
    conforms, results, _ = shacl_validate(graph, shacl_graph=shapes)
    messages = [str(m) for m in results.objects(None, SH.resultMessage)]
    return conforms, messages


def fixture_class(fixture):
    return Path(fixture).name.split("-", 1)[0]


def derived_invalid(fixture, slot, replacement, header):
    """The fixture, without its leading comments, with the last item of slot's
    list replaced, under the header."""
    lines = Path(fixture).read_text().splitlines()
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    start = lines.index(f"{slot}:")
    end = start + 1
    while end < len(lines) and lines[end].startswith("  - "):
        end += 1
    if end == start + 1:
        sys.exit(f"{fixture}: {slot} is not a list")
    lines[end - 1] = f"  - {replacement}"
    return "\n".join(header + lines) + "\n"


def records_document(bundle, class_name, pattern):
    graph = [typed(bundle.view, class_name, yaml.safe_load(Path(f).read_text())) for f in sorted(glob.glob(pattern))]
    return json.dumps({"@context": bundle.context, "@graph": graph}, indent=2, ensure_ascii=False) + "\n"


def invalid_class(text):
    for line in text.splitlines():
        if line.startswith("# class:"):
            return line.removeprefix("# class:").strip()
    return "GenericClaim"


def examples(mode):
    bundle = Bundle()
    view = bundle.view

    if mode == "generate":
        for invalid, derivation in DERIVED_INVALID.items():
            Path(invalid).write_text(derived_invalid(*derivation))
            print(f"✅ wrote {invalid}")
        for path, (class_name, pattern) in RECORDS.items():
            Path(path).parent.mkdir(exist_ok=True)
            Path(path).write_text(records_document(bundle, class_name, pattern))
            print(f"✅ wrote {path}")
        for fixture, example in EXAMPLES.items():
            Path(example).write_text(build(bundle, fixture_class(fixture), fixture))
            print(f"✅ wrote {example}")
        for invalid, example in INVALID_JSONLD.items():
            class_name = invalid_class(Path(invalid).read_text())
            Path(example).write_text(build(bundle, class_name, invalid))
            print(f"✅ wrote {example}")
        return

    failures = 0
    store = record_store()
    classes = hierarchy()
    for invalid, derivation in DERIVED_INVALID.items():
        if not Path(invalid).exists() or Path(invalid).read_text() != derived_invalid(*derivation):
            print(f"❌ {invalid} is stale: run make gen-claim-examples")
            failures += 1
    for path, (class_name, pattern) in RECORDS.items():
        if not Path(path).exists() or Path(path).read_text() != records_document(bundle, class_name, pattern):
            print(f"❌ {path} is stale: run make gen-claim-examples")
            failures += 1

    for fixture, example in EXAMPLES.items():
        class_name = fixture_class(fixture)
        text = build(bundle, class_name, fixture)
        if not Path(example).exists() or Path(example).read_text() != text:
            print(f"❌ {example} is stale: run make gen-claim-examples")
            failures += 1
            continue
        valid, output = json_schema_check(bundle, fixture, class_name)
        if valid:
            print(f"✅ {fixture}: conforms to JSON Schema")
        else:
            print(f"❌ {fixture}: JSON Schema violations\n{output}")
            failures += 1
        turtle = published_turtle(fixture)
        jsonld = rdflib.Graph().parse(data=text, format="json-ld")
        if isomorphic(jsonld, rdflib.Graph().parse(turtle, format="turtle")):
            print(f"✅ {example}: RDF matches {turtle}")
        else:
            print(f"❌ {example}: RDF differs from {turtle} (stale? run make gen-rdf)")
            failures += 1
        for document, graph in (
            (example, lexical_graph(text, "json-ld")),
            (turtle, lexical_graph(turtle.read_text(), "turtle")),
        ):
            conforms, messages = shacl_report(with_store(graph, store, class_name), bundle.shapes)
            if conforms:
                print(f"✅ {document}: conforms to SHACL")
            else:
                print(f"❌ {document}: SHACL violations {messages}")
                failures += 1
        data = yaml.safe_load(Path(fixture).read_text())
        if any(c.get("selector") for c in data.get("hasEvidenceCitation", [])):
            graph = rdflib.Graph().parse(data=text, format="json-ld")
            changed = rdflib.Graph().parse(data=build(bundle, class_name, fixture, change_selector(data)), format="json-ld")
            source = rdflib.URIRef(view.get_uri(view.get_slot("source"), expand=True))
            cited = lambda g: set(g.objects(None, source))
            records = lambda g: {t for t in with_store(g, store) if t[0] in cited(graph)}
            if cited(changed) == cited(graph) and records(changed) == records(graph) and not isomorphic(changed, graph):
                print(f"✅ {example}: changing a selector changes the citation, not the cited Evidence IRIs or records")
            else:
                print(f"❌ {example}: changing a selector changed the cited Evidence, or nothing")
                failures += 1
        if class_name in OPEN_BASES:
            base = OPEN_BASES[class_name]
            graph = with_store(lexical_graph(text, "json-ld"), store) + classes
            conforms, messages = shacl_report(as_extension(view, graph, class_name), bundle.shapes)
            if conforms:
                print(f"✅ {example} as an outside {base} subclass: conforms to the open {base} shape")
            else:
                print(f"❌ {example} as an outside {base} subclass: SHACL violations {messages}")
                failures += 1
            conforms, _ = shacl_report(as_extension(view, graph, class_name, without="assertedBy"), bundle.shapes)
            if not conforms:
                print(f"✅ {example} as an outside {base} subclass without assertedBy: the {base} shape rejects it")
            else:
                print(f"❌ {example} as an outside {base} subclass without assertedBy: SHACL accepts it")
                failures += 1
        elif class_name != "Evidence":
            graph = with_store(lexical_graph(text, "json-ld"), store) + classes
            conforms, messages = shacl_report(graph, bundle.shapes)
            if conforms:
                print(f"✅ {example} with the class hierarchy: conforms to its own shape and the open base shapes")
            else:
                print(f"❌ {example} with the class hierarchy: SHACL violations {messages}")
                failures += 1
            own = class_uri(view, class_name)
            shapes = rejecting_shapes(with_undeclared_field(view, graph, class_name), bundle.shapes)
            if shapes == {own}:
                print(f"✅ {example} with an undeclared field: only the {class_name} shape rejects it")
            else:
                print(f"❌ {example} with an undeclared field: rejected by {sorted(map(str, shapes)) or 'no shape'}")
                failures += 1

    for invalid in sorted(glob.glob(INVALID_GLOB)):
        content = Path(invalid).read_text()
        expected = content.splitlines()[0].removeprefix("# expect:").strip()
        class_name = invalid_class(content)
        valid, output = json_schema_check(bundle, invalid, class_name)
        if GRAPH_MARK in content:
            if valid:
                print(f"✅ {invalid}: JSON Schema accepts it alone")
            else:
                print(f"❌ {invalid}: expected JSON Schema to accept it alone\n{output}")
                failures += 1
        elif not valid and expected in output:
            print(f"✅ {invalid}: JSON Schema rejects it ({expected})")
        else:
            print(f"❌ {invalid}: expected JSON Schema rejection with '{expected}'\n{output}")
            failures += 1
        text = build(bundle, class_name, invalid)
        if invalid in INVALID_JSONLD:
            example = INVALID_JSONLD[invalid]
            if not Path(example).exists() or Path(example).read_text() != text:
                print(f"❌ {example} is stale: run make gen-claim-examples")
                failures += 1
        graph = lexical_graph(text, "json-ld")
        merged = with_store(graph, store, None if GRAPH_MARK in content else class_name)
        conforms, messages = shacl_report(merged, bundle.shapes)
        mark = next((line for line in content.splitlines() if line.startswith("# shacl: not enforced")), None)
        if mark:
            reason = mark.removeprefix("# shacl: not enforced").strip() or "(a LinkML rule; not expressed in SHACL)"
            if conforms:
                print(f"ℹ️  {invalid}: SHACL accepts it {reason}")
            else:
                print(f"❌ {invalid}: marked 'shacl: not enforced' but SHACL rejects it ({messages[0][:80]})")
                failures += 1
        elif not conforms:
            print(f"✅ {invalid}: SHACL rejects it ({messages[0][:80]})")
        else:
            print(f"❌ {invalid}: SHACL accepts it")
            failures += 1

    missing = set(INVALID_JSONLD) - set(glob.glob(INVALID_GLOB))
    for invalid in sorted(missing):
        print(f"❌ {invalid}: listed in INVALID_JSONLD but missing")
        failures += 1

    if failures:
        sys.exit(f"{failures} example check(s) failed")


def by_value(graph):
    """The graph with numeric literals in canonical form, to compare by value."""
    out = rdflib.Graph()
    for s, p, o in graph:
        if isinstance(o, rdflib.Literal) and isinstance(o.value, (int, float)) and not isinstance(o.value, bool):
            o = rdflib.Literal(float(o.value), datatype=o.datatype)
        out.add((s, p, o))
    return out


def playground(directory="data/playground", schema=SCHEMA):
    bundle = Bundle(schema)
    failures = 0
    fixtures = sorted(glob.glob(f"{directory}/*/*.yaml"))
    for fixture in fixtures:
        path = Path(fixture)
        text = build(bundle, fixture_class(fixture), fixture)
        path.with_suffix(".jsonld").write_text(text)
        turtle = path.with_suffix(".ttl")
        if not turtle.exists():
            print(f"❌ {turtle} is missing: run make gen-rdf")
            failures += 1
            continue
        jsonld = rdflib.Graph().parse(data=text, format="json-ld")
        if isomorphic(by_value(jsonld), by_value(rdflib.Graph().parse(turtle, format="turtle"))):
            print(f"✅ {path.with_suffix('.jsonld')}: RDF matches {turtle}")
        else:
            print(f"❌ {path.with_suffix('.jsonld')}: RDF differs from {turtle}")
            failures += 1
    print(f"Playground JSON-LD: {len(fixtures) - failures} of {len(fixtures)} match their Turtle")
    if failures:
        sys.exit(1)


if __name__ == "__main__":
    if sys.argv[1:2] == ["playground"] and len(sys.argv) <= 4:
        playground(*sys.argv[2:])
    elif len(sys.argv) != 2 or sys.argv[1] not in ("generate", "check"):
        sys.exit(__doc__)
